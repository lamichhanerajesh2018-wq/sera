// components/Avatar.tsx
// Renders a user's geometric avatar from a seed (their chosen avatarSeed, or
// their handle as a fallback). Pure, deterministic, no network — the same seed
// always looks the same. Used everywhere we used to show a 🕶️ emoji.
import { avatarSvg } from "@/lib/avatar";

export default function Avatar({
  seed,
  size = 36,
  className = "",
}: {
  seed: string;
  size?: number;
  className?: string;
}) {
  const svg = avatarSvg(seed, size);
  return (
    <span
      className={`inline-block shrink-0 overflow-hidden rounded-full ${className}`}
      style={{ width: size, height: size }}
      // The SVG is generated by us from a hashed seed — no user HTML is injected.
      dangerouslySetInnerHTML={{ __html: svg }}
      aria-hidden
    />
  );
}
